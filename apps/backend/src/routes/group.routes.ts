import { type Router as RouterType, Router } from 'express';
import { GroupService } from '../services/group.service.js';
import { GroupController } from '../controllers/group.controller.js';
import { authMiddleware } from '../middlewares/auth.middleware.js';
import { commentRateLimiter, inviteRateLimiter, roomCreateLimiter } from '../middlewares/rate-limit.middleware.js';
import { validateRequest } from '../middlewares/validate.js';
import { GroupInviteService } from '../services/group-invite.service.js';
import { InviteController } from '../controllers/invite.controller.js';
import { inviteByNicknameSchema } from '../validators/invite.validators.js';
import { GroupShareService } from '../services/group-share.service.js';
import { GroupShareContentService } from '../services/group-share-content.service.js';
import { GroupShareController } from '../controllers/group-share.controller.js';
import { createShareSchema } from '../validators/group-share.validators.js';
import { GroupRoomService } from '../services/group-room.service.js';
import { GroupRoomStateService } from '../services/group-room-state.service.js';
import { GroupRoomController } from '../controllers/group-room.controller.js';
import { createRoomSchema, roomAnswerSchema, roomReadySchema } from '../validators/group-room.validators.js';
import { GroupCommentService } from '../services/group-comment.service.js';
import { GroupCommentController } from '../controllers/group-comment.controller.js';
import { createCommentSchema, listCommentsSchema, resolveCommentSchema } from '../validators/group-comment.validators.js';

const router: RouterType = Router();

const service = new GroupService();
const controller = new GroupController(service);
const inviteController = new InviteController(new GroupInviteService());
const commentController = new GroupCommentController(new GroupCommentService());
const roomController = new GroupRoomController(new GroupRoomService(), new GroupRoomStateService());
const shareService = new GroupShareService();
const shareController = new GroupShareController(shareService, new GroupShareContentService(shareService));

router.post('/', authMiddleware, controller.create);
router.post('/join', authMiddleware, controller.join);
router.get('/', authMiddleware, controller.listMyGroups);
router.get('/:id', authMiddleware, controller.getById);
router.get('/:id/ranking', authMiddleware, controller.getRanking);
router.get('/:id/feed', authMiddleware, controller.getFeed);
router.post('/:id/invites', authMiddleware, inviteRateLimiter, validateRequest(inviteByNicknameSchema), inviteController.invite);
router.get('/:id/shares', authMiddleware, shareController.list);
router.post('/:id/shares', authMiddleware, validateRequest(createShareSchema), shareController.create);
router.get('/:id/shares/:shareId', authMiddleware, shareController.detail);
router.post('/:id/shares/:shareId/copy', authMiddleware, shareController.copy);
router.delete('/:id/shares/:shareId', authMiddleware, shareController.remove);
router.get('/:id/comments', authMiddleware, validateRequest(listCommentsSchema), commentController.list);
router.post('/:id/comments', authMiddleware, commentRateLimiter, validateRequest(createCommentSchema), commentController.create);
router.post('/:id/comments/:commentId/resolve', authMiddleware, validateRequest(resolveCommentSchema), commentController.resolve);
router.post('/:id/comments/:commentId/helpful', authMiddleware, commentController.helpful);
router.delete('/:id/comments/:commentId', authMiddleware, commentController.remove);
router.get('/:id/rooms', authMiddleware, roomController.list);
router.post('/:id/rooms', authMiddleware, roomCreateLimiter, validateRequest(createRoomSchema), roomController.create);
router.get('/:id/rooms/:roomId', authMiddleware, roomController.get);
router.post('/:id/rooms/:roomId/join', authMiddleware, roomController.join);
router.post('/:id/rooms/:roomId/start', authMiddleware, roomController.start);
router.post('/:id/rooms/:roomId/ready', authMiddleware, validateRequest(roomReadySchema), roomController.ready);
router.post('/:id/rooms/:roomId/answer', authMiddleware, validateRequest(roomAnswerSchema), roomController.answer);
router.delete('/:id/leave', authMiddleware, controller.leave);

export { router as groupRouter };
